def write_unit(num, data):
    out = []
    out.append("---")
    out.append(f'unitTitle: "{data["title"]}"')
    out.append(f'description: "{data["desc"]}"')
    out.append('icon: "🎙️"')
    out.append('color: "#E91E63"')
    out.append('targetLanguage: "en"')
    out.append('sourceLanguage: "en"')
    out.append('level: "A1"')
    out.append('courseId: "a1-speaking-course"')
    out.append('questionType: "speaking"')
    out.append("---")
    out.append("")

    for title, desc, exercises in data["lessons"]:
        assert len(exercises) == 10, f"{title} has {len(exercises)} exercises (expected 10)"
        out.append("---")
        out.append(f'lessonTitle: "{title}"')
        out.append(f'description: "{desc}"')
        out.append('icon: "🎙️"')
        out.append('color: "#FF9600"')
        out.append("---")
        out.append("")
        for sentence, words in exercises:
            out.append("[speaking]")
            out.append(f'sentence: "{sentence}"')
            out.append('srsWords: ' + " ".join(f'"{w}"' for w in words))
            out.append("")

    content = "\n".join(out).rstrip() + "\n"
    path = f"content/a1-speaking-unit-{num}.md"
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)
    total = sum(len(ex) for _, _, ex in data["lessons"])
    print(f"Wrote {path}: {len(data['lessons'])} lessons, {total} speaking questions")


def main():
    for num in (2, 3, 4, 5):
        write_unit(num, UNITS[num])
    print("Done.")


if __name__ == "__main__":
    main()
